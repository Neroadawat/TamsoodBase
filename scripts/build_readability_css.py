"""Generate the readability layer appended to web/design-refresh.css.

The three stylesheets set many labels at 9-13px, which is hard to read on a
projector and on phones.  Rather than editing each rule by hand, this script
reads every rule that sets a small font-size and emits the same selector with
a larger size, inside the same @media wrapper.  It also adds a short block of
hand-written spacing and density rules.  The block is replaced on each run.

    python -X utf8 scripts/build_readability_css.py          # write
    python -X utf8 scripts/build_readability_css.py --check  # verify only
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [ROOT / "web" / name for name in ("style.css", "theme.css", "design-refresh.css")]
TARGET = ROOT / "web" / "design-refresh.css"
START, END = "/* readability:start (generated by scripts/build_readability_css.py) */", "/* readability:end */"
# px size found -> px size used.  Display sizes (16px and up) are left alone.
LIFT = {6: 6, 8: 12, 9: 12, 10: 12.5, 11: 13, 12: 13.5, 13: 14.5, 14: 15, 15: 16}

MANUAL = """
body{line-height:1.7}
main p{max-width:76ch}
.reported-results p,.release-banner p{max-width:none}
.dataset-grid{grid-template-columns:repeat(auto-fit,minmax(270px,1fr))!important;gap:18px}
.dataset-card{grid-column:auto!important;display:flex;flex-direction:column}
.dataset-card>.button{margin-top:auto}
.dataset-card .dataset-capability{display:none}
.dataset-card h3{line-height:1.35}
.nav{line-height:1.45}
.muted,.case-note{line-height:1.7}
table td,table th{line-height:1.55}
.eyebrow{letter-spacing:.03em;text-transform:none}
.side-label{letter-spacing:.04em}
@media(max-width:760px){body{line-height:1.65}}
"""


def strip_generated(text: str) -> str:
    if START in text:
        return text[:text.index(START)].rstrip() + "\n" + text[text.index(END) + len(END):].lstrip()
    return text


def rules(css: str, wrapper: str = ""):
    """Yield (wrapper, selector, declarations) for every style rule."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    position = 0
    while position < len(css):
        brace = css.find("{", position)
        if brace == -1:
            return
        selector = css[position:brace].strip()
        depth, cursor = 1, brace + 1
        while cursor < len(css) and depth:
            depth += {"{": 1, "}": -1}.get(css[cursor], 0)
            cursor += 1
        inner = css[brace + 1:cursor - 1]
        if selector.startswith("@media"):
            yield from rules(inner, selector)
        elif not selector.startswith("@"):
            yield wrapper, selector, inner
        position = cursor


def generated() -> str:
    seen: dict[tuple[str, str], float] = {}
    for path in SOURCES:
        text = strip_generated(path.read_text(encoding="utf-8"))
        for wrapper, selector, declarations in rules(text):
            match = re.search(r"(?:^|;)\s*font-size\s*:\s*(\d+(?:\.\d+)?)px\s*(!important)?", declarations)
            if not match:
                continue
            size = float(match.group(1))
            if size.is_integer() and int(size) in LIFT and LIFT[int(size)] != size:
                seen[(wrapper, selector)] = LIFT[int(size)]
            else:
                seen.pop((wrapper, selector), None)  # a later rule set a size we keep
    plain = [f"{selector}{{font-size:{size:g}px}}" for (wrapper, selector), size in seen.items() if not wrapper]
    wrapped: dict[str, list[str]] = {}
    for (wrapper, selector), size in seen.items():
        if wrapper:
            wrapped.setdefault(wrapper, []).append(f"{selector}{{font-size:{size:g}px}}")
    media = [f"{wrapper}{{{''.join(items)}}}" for wrapper, items in wrapped.items()]
    return f"{START}\n" + "\n".join(plain + media) + "\n" + MANUAL.strip() + f"\n{END}\n"


def main() -> int:
    current = TARGET.read_text(encoding="utf-8")
    updated = strip_generated(current).rstrip() + "\n" + generated()
    if "--check" in sys.argv:
        if updated != current:
            print("readability block in web/design-refresh.css is stale; rebuild it", file=sys.stderr)
            return 1
    else:
        TARGET.write_text(updated, encoding="utf-8", newline="\n")
    print(f"readability rules: {updated.count('font-size', updated.index(START))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
